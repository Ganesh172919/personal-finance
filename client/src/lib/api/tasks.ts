/**
 * @fileoverview AI-Generated Task Management API
 *
 * Handles the lifecycle of actionable tasks produced by the AI financial
 * planning system. Tasks are the bridge between AI recommendations and
 * real financial actions -- the AI generates a plan, the plan is broken
 * into tasks, and the user can review, complete, or dismiss each one.
 *
 * Key concepts:
 * - **Task Lifecycle**: Tasks flow through statuses: `open` -> `completed`
 *   or `dismissed`. Completion may carry side-effects that the user can
 *   optionally "apply" to their financial data.
 * - **Task Effects (TaskEffect)**: When a task is completed, it can propose
 *   financial side-effects such as creating a transaction, advancing a goal,
 *   making a debt payment, or updating the user's profile. Effects are
 *   defined as a discriminated union on `type`.
 * - **Bucket**: Tasks are categorised by urgency horizon: 7-day, 30-day,
 *   or 365-day.
 * - **Apply Workflow**: After a task is completed, the user can call
 *   `applyTaskEffects` to actually execute the proposed side-effects on
 *   the server. This is an idempotent operation.
 *
 * All functions delegate to the shared `apiClient` for consistent
 * authentication, error handling, and organisation context.
 */

import { apiClient } from "./core";
import type { MutationSource, TransactionType } from "./transactions";

// Defines the valid execution lifecycle states for an AI-generated actionable task.
// Distinguishes actionable open tasks from completed actions or dismissed recommendations.
// Controls filtering queries and visual rendering status in task dashboard views.
/** Possible statuses a task can be in. */
export type TaskStatus = "open" | "completed" | "dismissed";

// Specifies supported periodic scheduling cadences for automated recurring financial tasks.
// Supports intervals ranging from none up to annual review cycles.
// Guides automated next-due-date calculations whenever recurring tasks are closed.
/** Recurrence cadence for automated task rescheduling */
export type TaskRecurrenceCadence = "none" | "daily" | "weekly" | "biweekly" | "monthly" | "quarterly" | "yearly";

// Configures recurrence behavior and ancestral lineage for repeatable financial tasks.
// Tracks active cadence intervals, subsequent scheduled deadlines, and generation depths.
// Enables automated reconstitution of follow-up tasks upon cycle completion.
export interface TaskRecurrence {
  cadence: TaskRecurrenceCadence;
  nextDueDate?: string;
  parentTaskId?: string;
  generation?: number;
}
// Represents the discriminated union of transactional side-effects produced by tasks.
// Encapsulates ledger mutations, goal contributions, debt paydowns, or profile adjustments.
// Provides a structured blueprint executed when task completion outcomes are confirmed.
/**
 * Discriminated union of financial side-effects a completed task can propose.
 * Each variant targets a different domain entity (transaction, goal, debt, profile).
 */
export type TaskEffect =
  | {
      type: "transaction";
      transaction: {
        amount: number;
        category: string;
        description: string;
        date?: string;
        tx_type: TransactionType;
      };
    }
  | {
      type: "goal_progress";
      goal_id: string;
      amount: number;
      /** "increment" adds to current, "set" replaces the value. */
      mode?: "increment" | "set";
    }
  | {
      type: "debt_payment";
      debt_id: string;
      amount: number;
    }
  | {
      type: "profile_update";
      updates: {
        annual_income?: number;
        monthly_expenses?: number;
        savings?: number;
      };
    };

// Represents a comprehensive AI-generated financial task entity with execution metadata.
// Encompasses scheduling horizons, priority tiers, step-by-step guidance, and impact notes.
// Tracks execution lifecycle status, applied financial mutations, and audit lineages.
/** A single actionable task generated by the AI planning system. */
export interface Task {
  _id: string;
  /** Traceability: which AI output / chat message produced this task. */
  source?: { agentOutputId?: string; chatMessageId?: string; requestId?: string };
  /** Urgency horizon: 7-day (immediate), 30-day (short-term), or 365-day (long-term). */
  bucket: 7 | 30 | 365;
  title: string;
  why: string;
  steps: string[];
  priority: "low" | "medium" | "high";
  expected_impact: string;
  kind: string;
  dueDate?: string;
  status: TaskStatus;
  completedAt?: string;
  /** Evidence captured when the user marks the task as completed. */
  completionEvidence?: {
    note?: string;
    completedAt?: string;
    effects?: TaskEffect[];
  };
  /** Timestamp and record of when proposed effects were applied. */
  appliedAt?: string;
  appliedSummary?: {
    transactions: string[];
    goals: string[];
    debts: string[];
    profileUpdated: boolean;
  };
  /** Status of the effect-application step: pending -> succeeded | failed. */
  applyStatus?: "pending" | "succeeded" | "failed";
  applyErrorCode?: string;
  applyIdempotencyKey?: string;
  /** Link to a UI action card that can deep-link to this task. */
  actionLinkId?: string;
  /** References to outcomes generated when effects were applied. */
  outcomeRefs?: string[];
  /** Automated recurrence cadence settings */
  recurrence?: TaskRecurrence;
}

// Deconstructs an AI-generated comprehensive financial plan into discrete actionable tasks.
// Preserves source provenance linking created tasks back to the parent agent run.
// Dispatches an authenticated POST request creating task batches in user storage.
/**
 * Ask the server to decompose an AI plan into individual tasks.
 * The optional `source` links each created task back to the originating
 * agent output or chat message for traceability.
 */
export async function createTasksFromPlan(payload: {
  source?: { agentOutputId?: string; chatMessageId?: string; requestId?: string };
  plan: any;
}): Promise<{ created: number; tasks: Task[] }> {
  return apiClient("/tasks/from-plan", {
    method: "POST",
    body: JSON.stringify(payload),
  });
}

// Directly provisions an individual actionable task with assigned priority and deadlines.
// Supports categorization across budget, debt, investment, and planning horizons.
// Dispatches an authenticated POST request to register the custom task entity.
/**
 * Create a single actionable task directly.
 */
export async function createTask(payload: {
  title: string;
  why: string;
  steps?: string[];
  priority?: "low" | "medium" | "high";
  expected_impact?: string;
  kind?: "cashflow" | "budget" | "debt" | "invest" | "goal" | "education" | "generic";
  bucket?: 7 | 30 | 365;
  due_days?: number;
  dueDate?: string | Date;
  recurrence?: {
    cadence: TaskRecurrenceCadence;
    parentTaskId?: string;
    generation?: number;
  };
}): Promise<{ task: Task }> {
  return apiClient("/tasks", {
    method: "POST",
    body: JSON.stringify(payload),
  });
}

// Retrieves a filtered list of user tasks constrained by status and retrieval limits.
// Clamps query limit values within safe bounds and defaults to active open items.
// Dispatches an authenticated GET request to populate client task list collections.
/**
 * Fetch tasks filtered by status, with a clamped limit (1-100, default 50).
 * Defaults to "open" tasks when no status is specified.
 */
export async function getTasks(params: { status?: TaskStatus; limit?: number } = {}): Promise<{ tasks: Task[] }> {
  const status = params.status || "open";
  // Clamp limit to a sane range to prevent accidental large fetches.
  const limit = Math.max(1, Math.min(100, Number(params.limit) || 50));
  const qs = new URLSearchParams({ status, limit: String(limit) });
  return apiClient(`/tasks?${qs.toString()}`);
}

// Updates the status of an existing task while capturing optional completion evidence.
// Transmits outcome notes, proposed financial effects, and recurrence instructions.
// Dispatches an authenticated PATCH request updating task attributes and next cycles.
/**
 * Update a task's status (and optionally attach completion evidence / effects).
 * This is a PATCH -- only the provided fields are overwritten.
 */
export async function updateTaskStatus(
  taskId: string,
  status: TaskStatus,
  options: {
    completed_at?: string;
    note?: string;
    effects?: TaskEffect[];
    completion_evidence?: { note?: string; completed_at?: string };
    apply_status?: "pending" | "succeeded" | "failed";
    apply_error_code?: string;
    recurrence?: {
      cadence: TaskRecurrenceCadence;
      parentTaskId?: string;
      generation?: number;
    };
  } = {}
): Promise<{ task: Task; next_task?: Task }> {
  return apiClient(`/tasks/${taskId}`, {
    method: "PATCH",
    body: JSON.stringify({ status, ...options }),
  });
}

// Commits the proposed financial mutations of a completed task into production records.
// Enforces idempotency keys to guarantee safe replays without duplicating ledger records.
// Dispatches an authenticated POST request triggering automated financial state updates.
/**
 * Execute the proposed side-effects of a completed task on the server.
 * This is an idempotent operation -- replaying the same request returns
 * the original result without duplicating effects.
 */
export async function applyTaskEffects(
  taskId: string,
  payload: { idempotency_key?: string; completed_at?: string; note?: string; effects?: TaskEffect[] } = {}
): Promise<{
  task: Task;
  applied_effects: {
    transactions: string[];
    goals: string[];
    debts: string[];
    profile_updated: boolean;
  };
  links: {
    action_link_id: string;
    task_id: string;
    transaction_ids: string[];
    goal_ids: string[];
    debt_ids: string[];
  };
  provenance: MutationSource;
  idempotent_replay?: boolean;
  request_id?: string;
}> {
  return apiClient(`/tasks/${taskId}/apply`, {
    method: "POST",
    body: JSON.stringify(payload),
  });
}

// Fetches the detailed specification and source history for a specific task ID.
// Unpacks originating agent context and user query snippets when linked to AI runs.
// Dispatches an authenticated GET request loading complete task details.
/** Fetch a single task by ID, including its source agent output if available. */
export async function getTaskById(taskId: string): Promise<{
  task: Task;
  source?: {
    agent_output: null | {
      id: string;
      request_id?: string;
      user_input_snippet: string;
      title?: string;
    };
  };
  request_id?: string;
}> {
  return apiClient(`/tasks/${taskId}`);
}

// Represents the token credentials and webhook route metadata for task externalization.
// Supplies the security access bearer token alongside the organization endpoint path.
// Facilitates webhook listener configuration across external project management tools.
export interface TaskWebhookTokenResult {
  webhook_token: string;
  webhook_path: string;
  request_id?: string;
}

// Retrieves or generates the organization-level webhook credential for task events.
// Secures inbound and outbound task synchronization pipelines against unauthorized access.
// Dispatches an authenticated GET request to obtain current webhook tokens.
/** Get or generate the organization's task webhook token */
export async function getTaskWebhookToken(): Promise<TaskWebhookTokenResult> {
  return apiClient("/tasks/webhook-token");
}

// Encapsulates parameters for forwarding designated tasks to third-party issue trackers.
// Targets systems like Linear, Todoist, Jira, or Slack with target webhook addresses.
// Bundles selected task identifiers and optional external bearer authorization headers.
export interface DispatchTasksWebhookPayload {
  target: "generic" | "linear" | "todoist" | "jira" | "slack";
  webhook_url: string;
  task_ids: string[];
  authorization?: string;
}

// Encapsulates external webhook dispatch results and HTTP transport diagnostics.
// Reports targeted service names, count of transmitted tasks, and remote status codes.
// Confirms synchronization success and supplies response diagnostic snippets for logs.
export interface DispatchTasksWebhookResult {
  success: boolean;
  target: string;
  dispatched_count: number;
  delivery_status: string;
  http_code: number;
  response_snippet: string;
  request_id?: string;
}

// Forwards selected tasks to an external tracker webhook formatted to its target schema.
// Translates task schemas into compatible external formats for Jira, Linear, or Slack.
// Dispatches an authenticated POST request triggering outbound integration delivery.
/** Dispatch selected tasks to an external webhook URL formatted for target tracker */
export async function dispatchTasksWebhook(
  payload: DispatchTasksWebhookPayload
): Promise<DispatchTasksWebhookResult> {
  return apiClient("/tasks/dispatch-webhook", {
    method: "POST",
    body: JSON.stringify(payload),
  });
}
