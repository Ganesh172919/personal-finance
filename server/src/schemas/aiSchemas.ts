/**
 * @fileoverview Zod validation schemas for AI-related API request bodies and query parameters.
 *
 * Exported schemas:
 *   processCommandBodySchema         - Validates AI command input (command text + optional narrative flag)
 *   whatIfScenarioBodySchema         - Validates what-if scenario parameters (v2 or legacy format)
 *   updateFinancialProfileBodySchema - Validates financial profile updates (age, income, expenses,
 *                                      savings, goals, debts, transactions, risk tolerance, etc.)
 *   addInvestmentBodySchema          - Validates adding a new investment entry
 *   agentOutputFeedbackBodySchema    - Validates thumbs up/down feedback on AI agent outputs
 *   recentAgentOutputsQuerySchema    - Validates query params for listing recent agent outputs
 *
 * Used by: aiRoutes, v1Routes
 *
 * Key validation rules:
 *   - Command text: required, 1-4000 chars
 *   - What-if scenarios support two formats: v2 (scenario_type + amount) and legacy (type + expense/income)
 *   - Financial profile: all fields optional, arrays of goals/debts/transactions validated individually
 *   - Investment: name required, amount must be positive
 *   - Feedback rating: enum "up" | "down"
 */
import { z } from "zod";

// Defines an enumeration schema for user investment risk tolerance levels.
// Restricts acceptable options to conservative, moderate, or aggressive profiles.
// Directs portfolio allocation algorithms and risk-adjusted advice parameters.
const riskToleranceSchema = z.enum(["conservative", "moderate", "aggressive"]);
// Validates an enumeration of user financial and investment experience tiers.
// Classifies user competence levels across beginner, intermediate, and expert.
// Influences complexity and depth of recommendations generated by the AI planner.
const investmentExperienceSchema = z.enum(["beginner", "intermediate", "expert"]);

// Validates structured financial target goals contained within user profiles.
// Enforces mandatory target and current amounts, deadlines, and priority rankings.
// Rejects unexpected properties to ensure consistent profile goal storage.
const financialGoalSchema = z
  .object({
    name: z.string().trim().min(1).max(120),
    target: z.number().nonnegative(),
    current: z.number().nonnegative(),
    deadline: z.string().trim().min(1).max(64),
    priority: z.number().int().positive().max(10)
  })
  .strict();

// Validates a liability or debt instrument entry recorded on a user profile.
// Enforces non-negative balances, interest rates, and required minimum payments.
// Captures loan categories to support debt avalanche and snowball calculations.
const debtSchema = z
  .object({
    name: z.string().trim().min(1).max(120),
    balance: z.number().nonnegative(),
    interest_rate: z.number().min(0).max(100),
    minimum_payment: z.number().nonnegative(),
    type: z.string().trim().min(1).max(60)
  })
  .strict();

// Validates an individual transaction record submitted within profile updates.
// Enforces numeric amount, category, description, and coerced date timestamps.
// Restricts transaction types to income, expense, or investment classifications.
const transactionSchema = z
  .object({
    amount: z.number(),
    category: z.string().trim().min(1).max(100),
    description: z.string().trim().min(1).max(250),
    date: z.coerce.date(),
    type: z.enum(["income", "expense", "investment"])
  })
  .strict();

// Validates request payloads submitting natural language commands to the AI engine.
// Enforces non-empty command text bounded within a maximum length of 4000 characters.
// Supports optional narrative configuration flags controlling response verbosity.
export const processCommandBodySchema = z
  .object({
    command: z.string().trim().min(1, "Command is required").max(4000),
    options: z
      .object({
        narrative: z.boolean().optional(),
      })
      .strict()
      .optional(),
  })
  .strict();

// Validates projection assumptions for financial what-if forecasting simulations.
// Accepts simulation durations in months alongside return and inflation percentages.
// Bounds parameters within realistic financial simulation constraints.
const scenarioAssumptionsSchema = z
  .object({
    months: z.number().int().positive().max(120).optional(),
    expected_return_pct: z.number().min(-100).max(100).optional(),
    inflation_pct: z.number().min(-50).max(100).optional(),
  })
  .strict();

// Validates modern V2 parameters for executing what-if financial simulations.
// Enforces explicit scenario classification types and positive currency amounts.
// Accommodates optional textual descriptions and forecasting model assumptions.
const scenarioParametersV2Schema = z
  .object({
    scenario_type: z.enum(["expense", "income", "investment"]),
    amount: z.number().positive(),
    description: z.string().trim().max(500).optional(),
    assumptions: scenarioAssumptionsSchema.optional(),
  })
  .strict();

// Validates backwards-compatible legacy parameters for what-if scenario analyses.
// Supports older schemas supplying separate non-negative income or expense fields.
// Facilitates gradual API client migration without breaking legacy callers.
const scenarioParametersLegacySchema = z
  .object({
    type: z.enum(["expense", "income", "investment"]).optional(),
    expense: z.number().nonnegative().optional(),
    income: z.number().nonnegative().optional(),
    description: z.string().trim().max(500).optional(),
  })
  .strict();

// Validates the root payload for running automated what-if financial projections.
// Uses a union schema to seamlessly accept either modern V2 or legacy formats.
// Ensures strict property validation across simulation request envelopes.
export const whatIfScenarioBodySchema = z
  .object({
    parameters: z.union([scenarioParametersV2Schema, scenarioParametersLegacySchema]),
  })
  .strict();

// Validates incoming HTTP payloads requesting updates to a user's financial profile.
// Supports partial updates to earnings, expenses, goals, liabilities, and risk tolerance.
// Enforces strict schema constraints to keep user financial states sanitized.
export const updateFinancialProfileBodySchema = z
  .object({
    age: z.number().int().positive().max(120).optional(),
    annual_income: z.number().nonnegative().optional(),
    monthly_expenses: z.number().nonnegative().optional(),
    savings: z.number().optional(),
    goals: z.array(financialGoalSchema).optional(),
    debts: z.array(debtSchema).optional(),
    transactions: z.array(transactionSchema).optional(),
    onboardingCompletedAt: z.coerce.date().optional(),
    onboardingVersion: z.string().trim().min(1).max(32).optional(),
    risk_tolerance: riskToleranceSchema.optional(),
    investment_experience: investmentExperienceSchema.optional()
  })
  .strict();

// Validates request payloads creating a new portfolio investment holding entry.
// Enforces a non-empty investment name, positive valuation, and optional dates.
// Sanitizes input fields using strict schema evaluation to prevent malformed data.
export const addInvestmentBodySchema = z
  .object({
    name: z.string().trim().min(1).max(120),
    type: z.string().trim().max(60).optional(),
    amount: z.number().positive(),
    date: z.coerce.date().optional()
  })
  .strict();

// Feedback schema (rating, reason code, capped correction) lives in ./aiFeedback.
export { agentOutputFeedbackBodySchema } from "./aiFeedback";

// Validates query parameters for fetching historical AI agent output records.
// Coerces and constrains integer limits up to a maximum of 100 recent entries.
// Defaults to returning 20 records when pagination limits are omitted.
export const recentAgentOutputsQuerySchema = z
  .object({
    limit: z.coerce.number().int().positive().max(100).optional().default(20),
  })
  .strict();

// Validates query parameters for retrieving organization member financial profiles.
// Controls transaction inclusion flags, transaction count limits, and currency overrides.
// Enforces strict parameter validation to keep profile retrieval queries sanitized.
export const getFinancialProfileQuerySchema = z
  .object({
    includeTransactions: z.enum(["true", "false"]).optional(),
    txLimit: z.coerce.number().int().positive().max(100).optional(),
    currency: z.enum(["USD", "EUR", "GBP", "INR", "CAD", "AUD", "JPY"]).optional(),
  })
  .strict();
